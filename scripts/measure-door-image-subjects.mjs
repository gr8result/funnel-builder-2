// Measures where the door actually sits inside wide studio door shots, so door cards can show the
// door itself at full height instead of a small door lost in a mostly-empty landscape canvas.
// Writes lib/product-library/doorImageSubjects.js. Only wide images whose non-white content is a
// narrow band are recorded; full-bleed photos (facades, lifestyle shots) are left uncropped.
//
// Usage: node scripts/measure-door-image-subjects.mjs
import fs from "node:fs";
import sharp from "sharp";

const CATALOGUE = "data/product-library/catalogues/exterior/AU-WINDOWS-ENTRY-DOORS-GARAGE-DOORS-CATALOGUE.json";
const OUTPUT = "lib/product-library/doorImageSubjects.js";
const WHITE_THRESHOLD = 235;
const PADDING = 0.02;

const catalogue = JSON.parse(fs.readFileSync(CATALOGUE, "utf8"));
const urls = [...new Set(catalogue.products
  .filter((product) => product.family_key === "entry-doors" && product.primary_image_url)
  .map((product) => product.primary_image_url))];

async function load(url) {
  if (!/^https?:/i.test(url)) return fs.readFileSync(`public${url}`);
  const response = await fetch(url);
  if (!response.ok) throw new Error(`HTTP ${response.status}`);
  return Buffer.from(await response.arrayBuffer());
}

const subjects = {};
const skipped = [];
for (const url of urls) {
  try {
    const { data, info } = await sharp(await load(url)).flatten({ background: "#ffffff" }).greyscale().raw().toBuffer({ resolveWithObject: true });
    if (info.width <= info.height) continue;
    let x0 = info.width, y0 = info.height, x1 = 0, y1 = 0;
    for (let y = 0; y < info.height; y += 1) {
      for (let x = 0; x < info.width; x += 1) {
        if (data[y * info.width + x] >= WHITE_THRESHOLD) continue;
        if (x < x0) x0 = x;
        if (x > x1) x1 = x;
        if (y < y0) y0 = y;
        if (y > y1) y1 = y;
      }
    }
    const box = {
      x0: Math.max(0, x0 / info.width - PADDING),
      x1: Math.min(1, (x1 + 1) / info.width + PADDING),
      y0: Math.max(0, y0 / info.height - PADDING),
      y1: Math.min(1, (y1 + 1) / info.height + PADDING),
    };
    if (box.x1 - box.x0 > 0.7) continue;
    subjects[url] = { width: info.width, height: info.height, ...Object.fromEntries(Object.entries(box).map(([key, value]) => [key, Number(value.toFixed(4))])) };
  } catch (error) {
    skipped.push(`${url} (${error.message})`);
  }
}

fs.writeFileSync(OUTPUT, `// Generated by scripts/measure-door-image-subjects.mjs - do not edit by hand.
// Door subject box (fractions of the image) inside wide studio door shots.
export const DOOR_IMAGE_SUBJECTS = ${JSON.stringify(subjects, null, 2)};
`);
console.log(`${Object.keys(subjects).length} door subject boxes written to ${OUTPUT}`);
if (skipped.length) console.log(`Skipped:\n${skipped.join("\n")}`);
