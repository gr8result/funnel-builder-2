// Local drawing trace; reference coordinates are used only to frame inspection crops.
import fs from 'node:fs';
import path from 'node:path';
import { createCanvas, loadImage } from '@napi-rs/canvas';
import { detectVectorWalls } from '../components/construction-estimation/ai-plan-takeoff/geometry/vectorWalls.js';
import { buildLocalVectorAnalysis } from '../components/construction-estimation/ai-plan-takeoff/ai-integration/localVectorAnalysis.js';
import { convertAiTakeoffDetections } from '../components/construction-estimation/ai-plan-takeoff/ai-integration/adapter.js';
const page = Number(process.argv[2] || 4);
const dir = `artifacts/test-results/takeoff-quick-accuracy-cache/JESMOND-ROAD-INDOOROOPILLY-CONTRUCTION-I-p${page}`;
const out = process.argv[3] || 'artifacts/test-results/takeoff-drawing-trace-20261101';
fs.mkdirSync(out, { recursive: true });
const input = JSON.parse(fs.readFileSync(path.join(dir, 'application-input.json')));
const image = await loadImage(path.join(dir, 'application-raster.png'));
const canvas = createCanvas(image.width, image.height), g = canvas.getContext('2d'); g.drawImage(image, 0, 0);
const raster = g.getImageData(0, 0, image.width, image.height); raster.storedPixelsPerMm = input.storedPixelsPerMm;
const detected = detectVectorWalls(input.vectorSegments, { ...input, raster });
const context = { jobId: 'diagnosis-copy', takeoffId: 'diagnosis-copy', documentHash: 'diagnosis', pixelsPerMm: input.pixelsPerMm, pages: [input], completedWallRuns: [], placedOpenings: [], completedFloorplans: [], sheetLevels: { [page]: page === 4 ? 'Upper Floor' : 'Lower Floor' } };
const prepared = buildLocalVectorAnalysis({ planPage: input, detected, pixelsPerMm: input.pixelsPerMm, level: context.sheetLevels[page], context, runId: 'diagnosis' });
const canonical = convertAiTakeoffDetections(prepared.batch, context);
fs.writeFileSync(path.join(out, `page-${page}.json`), JSON.stringify({ detected, prepared, canonical }, null, 2));
const reference = JSON.parse(fs.readFileSync('.claude/worktrees/ai-takeoff-geometry/recovery/plan-references/jesmond-road/reference.json'));
const points = reference.walls.filter(w => w.page === page).flatMap(w => [w.a, w.b]);
const k = image.width / input.logicalWidth;
const bounds = [Math.min(...points.map(p => p.x)) - 45, Math.min(...points.map(p => p.y)) - 45, Math.max(...points.map(p => p.x)) + 45, Math.max(...points.map(p => p.y)) + 45];
const width = (bounds[2] - bounds[0]) * k, height = (bounds[3] - bounds[1]) * k;
const crop = createCanvas(Math.round(height), Math.round(width)); const cg = crop.getContext('2d');
cg.translate(0, width); cg.rotate(-Math.PI / 2);
cg.drawImage(image, bounds[0] * k, bounds[1] * k, width, height, 0, 0, width, height);
fs.writeFileSync(path.join(out, `page-${page}-drawing.png`), crop.toBuffer('image/png'));
console.log(JSON.stringify({ stats: detected.stats, walls: detected.walls, openings: detected.openings, labels: input.textItems.filter(t => /14028|balustrade|stairs|\bUP\b/.test(t.text)) }, null, 2));
