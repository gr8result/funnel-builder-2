import assert from "node:assert/strict";
import fs from "node:fs";
import sharp from "sharp";
import { getEffectiveProductCatalogue, saveCarpetQuoteHistory } from "../lib/product-library/catalogueService.js";
import { mergeFlooringCatalogue } from "../lib/product-library/flooringCatalogue.js";
import { appendCarpetQuote, carpetEstimateRates } from "../lib/builders/carpetSelection.js";
import { applyFlooringChoice, connectFlooringSelectionsToQuotation, flooringLines, flooringSelectionPatch, flooringTakeoffData, suggestedFlooringAreas } from "../lib/builders/flooringSelection.js";
import { quotationSectionsForFinalBoq } from "../lib/construction-estimation/finalQuotationBoq.js";
import { createEstimateBuilderWorkbookDefaults } from "../lib/construction-estimation/estimateBuilderWorkbookDefaults.js";
import { calculateEstimateBuilderWorkbook } from "../lib/construction-estimation/estimateBuilderWorkbookCalculations.js";

const catalogue = JSON.parse(fs.readFileSync("data/product-library/catalogues/flooring/AU-GODFREY-HIRST-FLOORING-CATALOGUE.json"));
const products = getEffectiveProductCatalogue().products.filter((p) => p.attributes?.supplierKey === "godfrey-hirst");
assert.equal(products.length, 65);
assert.equal(products.flatMap((p) => p.variants).length, 684);
assert.equal(new Set(products.flatMap((p) => p.variants.map((v) => v.variantId))).size, 684);
assert.ok(products.some((p) => /Hycraft/i.test(p.brand)));
let images = 0;
for (const p of products) {
  assert.equal(p.supplier, "");
  assert.equal(p.priceStatus, "quote_required");
  assert.ok(p.description && p.attributes.carpetSpecs.fibre && p.attributes.carpetSpecs.rollWidthM && p.attributes.carpetSpecs.specificationUrl);
  const html = fs.readFileSync(`data/product-library/source-evidence/godfrey-hirst-flooring/${p.attributes.manufacturerProductId}.html`, "utf8");
  const source = JSON.parse(html.match(/<script id="__NEXT_DATA__" type="application\/json">([\s\S]*?)<\/script>/)[1]).props.pageProps.product;
  assert.equal(source.variants.length, p.variants.length);
  for (const v of p.variants) {
    const official = source.variants.find((item) => item.globalItemId === v.sku);
    assert.equal(official.name, v.colour); assert.equal(official.colourId, v.colourCode);
    assert.equal(v.regularPricePerM2, null); assert.equal(v.packCoverageM2, null);
    assert.ok(v.officialImageUrl.includes(`/variants/${v.sku}/`));
    if (v.imageUrl) { const info = await sharp(`public${v.imageUrl}`).metadata(); assert.ok(info.width > 0 && info.height > 0); images++; }
    else assert.equal(v.sku, "0241360780", "Only the documented manufacturer 404 may lack an image");
  }
}
assert.equal(images, 683);
const p = products.find((p) => p.range === "Inspirational");
const cloudy = p.variants.find((v) => v.colour === "Cloudy Day"), other = p.variants.find((v) => v.colour !== "Cloudy Day");
assert.equal(cloudy.colourCode, "725");
const byId = (id) => products.find((p) => p.productId === id);
const wb = createEstimateBuilderWorkbookDefaults();
wb.projectRooms = [18.4, 12.6, 12.4, 13.1, 6.2].map((areaM2, i) => ({ name: `Measured room ${i + 1}`, areaM2, flooringType: "carpet" }));
wb.quotation.CARPETS.rows[0].quantity = "62.7";
wb.data.inputDataSheet.rows.floorFinishCarpetsM2 = { value: "62.7" };
const takeoff = flooringTakeoffData(wb);
let areas = suggestedFlooringAreas(wb.projectRooms.map((r) => r.name), takeoff);
assert.equal(areas.length, 5, "measured room totals are not added twice via an aggregate area");
assert.deepEqual(areas.map((a) => a.areaM2), [18.4, 12.6, 12.4, 13.1, 6.2]);
areas = applyFlooringChoice(areas, areas.map((a) => a.id), { productId: p.productId, variantId: cloudy.variantId, wastagePct: 10 });
const rates = carpetEstimateRates(wb.quotation);
assert.equal(rates.combinedAllowancePerM2ExGst, 75);
assert.equal(carpetEstimateRates({ CARPETS: { rows: [{ id: "lump-sum", item: "Carpet quote", unit: "ITEM", excelRate: "$3721.82" }, ...wb.quotation.CARPETS.rows] } }).combinedAllowancePerM2ExGst, 75, "a lump-sum quote must never become a per-square-metre material allowance");
let lines = flooringLines(areas, { productById: byId, carpetRates: rates });
assert.equal(lines[0].netAreaM2, 62.7);
assert.equal(lines[0].requiredAreaM2, null); assert.equal(lines[0].packs, null); assert.equal(lines[0].materialCost, null);
assert.equal(lines[0].internalEstimateExGst, 4702.5);
areas = applyFlooringChoice(areas, [areas[2].id], { productId: p.productId, variantId: other.variantId });
assert.equal(areas.filter((a) => a.variantId === cloudy.variantId).length, 4);
const quote = { supplier: "Regression retailer", quoteDate: "2026-10-03", materialPerM2ExGst: 40, underlayPerM2ExGst: 6, installationPerM2ExGst: 10, otherExGst: 20 };
assert.throws(() => appendCarpetQuote([], { ...quote, supplier: "" }));
assert.throws(() => appendCarpetQuote([], { ...quote, underlayPerM2ExGst: "" }));
const history = appendCarpetQuote([], quote);
assert.equal(appendCarpetQuote(history, quote).length, 1);
assert.equal(appendCarpetQuote(history, { ...quote, materialPerM2ExGst: 41 }).length, 2);
const options = { [cloudy.variantId]: { estimatedOrderAreaM2: 56, orderNetAreaM2: 50.3, estimate: { materialPerM2ExGst: 30, underlayPerM2ExGst: 7, installationPerM2ExGst: 12, otherExGst: 50 }, supplierQuoteHistory: history, selectedQuoteId: history[0].id } };
lines = flooringLines(areas, { productById: byId, carpetRates: rates, carpetOptions: options });
const line = lines.find((l) => l.variantId === cloudy.variantId);
assert.equal(line.selectedCostExGst, 3064.8); assert.equal(line.internalEstimateExGst, 2685.7); assert.equal(line.variation, 417.01);
const patch = flooringSelectionPatch({}, areas, { productById: byId, carpetRates: rates, carpetOptions: options });
const book = { rooms: [{ rows: [patch] }] };
const connected = connectFlooringSelectionsToQuotation(wb, book, { productById: byId });
const connectedAgain = connectFlooringSelectionsToQuotation(connected, book, { productById: byId });
const selectedRows = connectedAgain.quotation.CARPETS.rows.filter((r) => r.source === "client-selections-flooring");
assert.equal(selectedRows.length, 2); assert.equal(connectedAgain.procurement.items.length, connected.procurement.items.length);
assert.equal(connectedAgain.quotation.CARPETS.rows[0].quantity, 0, "replaced allowance is not charged a second time");
const calculated = calculateEstimateBuilderWorkbook(connectedAgain);
const boq = quotationSectionsForFinalBoq(calculated.quotation).flatMap((s) => s.rows).filter((r) => r.source === "client-selections-flooring");
assert.equal(boq.length, 2, "carpet reaches actual Project Estimate/BOQ calculation");
assert.equal(boq.find((r) => r.variantId === cloudy.variantId).qty, 50.3);
assert.equal(boq.find((r) => r.variantId === cloudy.variantId).locationSchedule.length, 4);
assert.equal(boq.find((r) => r.variantId === cloudy.variantId).sourceOfRate, "Retailer quote (allocated total)");
assert.equal(boq.find((r) => r.variantId === other.variantId).quoteRequired, true, "commercial BOQ exports retain the quote-required status");
assert.equal(boq.find((r) => r.variantId === other.variantId).sourceOfRate, "Internal carpet allowance");
assert.equal(connected.procurement.items.find((r) => r.variantId === cloudy.variantId).qty, 56);
const procurementLine = connected.procurement.items.find((r) => r.variantId === cloudy.variantId);
assert.equal(Math.round(procurementLine.qty * procurementLine.estimatedRate * 100) / 100, procurementLine.estimatedTotal, "procurement quantity times allocated rate includes every quoted component");
assert.equal(procurementLine.materialRateExGst, 40, "actual material rate remains separate from the allocated total");
assert.equal(procurementLine.quoteRowId, `flooring:${cloudy.variantId}`, "commercial procurement links to its BOQ quotation row");
assert.equal(connected.procurement.items.find((r) => r.variantId === other.variantId).qty, null, "unknown carpet order is never the net area or net plus 10%");
const cleared = connectFlooringSelectionsToQuotation(connected, { rooms: [] }, { productById: byId });
assert.equal(cleared.quotation.CARPETS.rows[0].quantity, "62.7", "clearing selection restores the baseline");
assert.deepEqual(flooringSelectionPatch({}, [], { carpetOptions: options }).guidedSelection.carpetOptions[cloudy.variantId].supplierQuoteHistory, history, "clearing the selected areas retains the project's retailer history");
const roomSources = flooringTakeoffData({ clientSelectionsBook: { rooms: [{ name: "Bathroom Accessories", id: "guided-accessories" }] }, projectRooms: [{ name: "Actual Bedroom", geometry: { widthMm: 4000, lengthMm: 3500 } }], aiPlanTakeoffJob: { aiAnalysis: { rooms: [{ name: "Assumed Room", areaM2: 99, basis: "ASSUMED" }] } } });
assert.deepEqual(roomSources.rooms.map((r) => [r.name, r.areaM2]), [["Actual Bedroom", 14]], "use known geometry, omit category containers and assumed AI rooms");
const restored = flooringLines(patch.guidedSelection.flooringAreas, { carpetRates: rates, carpetOptions: options });
assert.equal(restored[0].brand, line.brand, "snapshots survive a missing catalogue record");
const changedAreas = areas.map((a, i) => i === 0 ? { ...a, areaM2: 19 } : a);
assert.equal(flooringLines(changedAreas, { productById: byId, carpetOptions: options })[0].estimatedOrderAreaM2, null, "changed rooms invalidate stale order estimates");
const imported = structuredClone(catalogue); imported.products[0].variants[0].supplierQuoteHistory = history;
const refreshed = mergeFlooringCatalogue(imported, catalogue);
assert.equal(refreshed.products.length, catalogue.products.length);
assert.deepEqual(refreshed.products[0].variants[0].supplierQuoteHistory, history);
assert.equal(refreshed.products[0].variants[0].firstImportedAt, imported.products[0].variants[0].firstImportedAt);
console.log(`Carpet checks passed: ${products.length} ranges, 684 colours, ${images} verified local swatches; known rooms, roll quantities, retailer history, allowances, actual estimate/BOQ and procurement, update/clear and refresh preservation.`);
