import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import { masterJobId, masterJobAliases, linkTakeoffToMasterJob, mergeMasterJobSummaries } from '../lib/construction-estimation/masterJob.js';

const a = { jobId: '91ad23fa-ea59-4928-a716-500af54f87a3', projectId: 'legacy-commercial-a', data: { inputDataSheet: { rows: { projectName: { value: 'Michael and Sarah Johnson' } } } } };
const b = { ...a, jobId: 'f364dbb5-864c-473b-94ce-eae216a55027' };
const source = readFileSync('components/estimate-builder/EstimateBuilderWorkbook.js', 'utf8');
const fn = source.match(/function deriveTakeoffEngineJobId\([^]*?\n\}/)?.[0];
assert.ok(fn);
const derive = new Function('masterJobId', `${fn}; return deriveTakeoffEngineJobId;`)(masterJobId);
assert.equal(derive(a), a.jobId);
assert.equal(derive({ ...a, openedFileName: 'renamed.gr8job', registeredJob: { jobId: 'other-commercial-id' } }), a.jobId);
assert.equal(derive({ openedFileName: 'Michael and Sarah Johnson.gr8job' }), '', 'A filename cannot supply an owner ID');
assert.equal(derive({}), '', 'An unopened job cannot share an unsaved placeholder ID');
assert.notEqual(derive(a), derive(b), 'Two jobs with the same customer/name remain distinct');
assert.ok(masterJobAliases(a).includes('legacy-commercial-a'));
const empty = linkTakeoffToMasterJob(a);
assert.equal(empty.jobId, a.jobId);
assert.equal(empty.masterJobId, a.jobId);
assert.equal(linkTakeoffToMasterJob(a, empty).takeoffId, empty.takeoffId);
assert.throws(() => linkTakeoffToMasterJob({}, {}), /Create or open/);
assert.throws(() => linkTakeoffToMasterJob(b, empty), /different master/);
assert.throws(() => linkTakeoffToMasterJob(b, empty, { importLegacy: true }), /different master/);
const legacy = { takeoffId: 'old-takeoff-id', associatedProjectId: 'legacy-commercial-a', completedFloorplans: [{ id: 'measured' }] };
const migrated = linkTakeoffToMasterJob(a, legacy);
assert.equal(migrated.masterJobId, a.jobId);
assert.equal(migrated.takeoffId, legacy.takeoffId);
assert.deepEqual(migrated.completedFloorplans, legacy.completedFloorplans);
assert.equal(legacy.masterJobId, undefined, 'Migration does not mutate the source');
assert.throws(() => linkTakeoffToMasterJob(a, { ...legacy, associatedProjectId: 'legacy-commercial-a-other' }), /not linked/);
assert.equal(linkTakeoffToMasterJob(a, { ...legacy, associatedProjectId: 'old-detached' }, { importLegacy: true }).masterJobId, a.jobId);
assert.equal(linkTakeoffToMasterJob(a, { ...legacy, jobId: 'old-module-id' }, { storedInMaster: true }).masterJobId, a.jobId);
const local = { key: `job:${a.jobId}`, jobId: a.jobId, savedAt: '2026-10-01' };
const cloud = { key: 'cloud:a', localJobKey: local.key, projectId: a.projectId };
assert.deepEqual(mergeMasterJobSummaries([local], []), [local], 'Local jobs appear without a cloud workspace');
assert.deepEqual(mergeMasterJobSummaries([local], [cloud]), [local], 'Cloud registration cannot duplicate a job');
console.log('PASS permanent master IDs, equal-name isolation, shared picker, legacy migration and foreign-job rejection');
