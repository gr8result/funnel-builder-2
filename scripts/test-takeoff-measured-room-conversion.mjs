import assert from 'node:assert/strict';
import { detectRoomBoundary } from '../components/construction-estimation/ai-plan-takeoff/ai-integration/roomGeometry.js';
import { refreshAnalysisReadiness } from '../components/construction-estimation/ai-plan-takeoff/ai-integration/analysisReadiness.js';
const polygon = [{ x: .1, y: .1 }, { x: .8, y: .1 }, { x: .8, y: .4 }, { x: .4, y: .4 }, { x: .4, y: .8 }, { x: .1, y: .8 }];
const input = { id: 'measured-room', name: 'Living', polygon, boundaryClosed: true, confidence: .95, lineworkVerified: true };
const context = { page: 2, level: 'Ground Floor', width: 1000, height: 800, pixelsPerMm: .1, measuredBoundary: true };
const result = detectRoomBoundary(input, context);
assert.deepEqual(result.polygon, polygon.map(p => ({ x: p.x * 1000, y: p.y * 800 })), 'measured concave wall faces are converted once without re-snapping');
assert.equal(result.detectionMethod, 'wall-linework');
assert.ok(result.areaM2 > 0);
assert.equal(detectRoomBoundary(input, { ...context, measuredBoundary: false }).detectionMethod, 'ai-and-wall-edges', 'a provider flag cannot establish locally measured provenance');
const invalid = detectRoomBoundary({ ...input, polygon: [{ x: .1, y: .1 }, { x: .8, y: .8 }, { x: .8, y: .1 }, { x: .1, y: .8 }] }, context);
assert.equal(invalid.areaM2, null);
assert.equal(invalid.reviewRequired, true, 'measured provenance cannot admit invalid geometry');
const report = refreshAnalysisReadiness({ status: 'appended', completedAt: 'old', rooms: [invalid], review: [] });
assert.equal(report.status, 'review');
assert.equal(report.completedAt, null);
assert.equal(report.counts.roomsForReview, 1);
assert.deepEqual(refreshAnalysisReadiness(report), report, 'repeated updates do not duplicate the review warning');
console.log('Measured-room conversion preserves wall faces, validates geometry and prevents false completion for scans.');
