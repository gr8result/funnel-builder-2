import assert from 'node:assert/strict';
import fs from 'node:fs';
import { CURRENT_BUILDER_WORKSPACE_ID } from '../lib/builders/currentBuilderSeed.js';
import { tenantStorageKey } from '../lib/builders/tenantScope.js';
import { browserTenantKey, builderLocalStorage, scopeBrowserWorkbook } from '../lib/builders/browserTenantStorage.js';
import { createEstimateBuilderWorkbookDefaults } from '../lib/construction-estimation/estimateBuilderWorkbookDefaults.js';
import { normaliseStandardInclusions } from '../lib/builders/standardInclusions.js';
import { filterProductsForProductLibraryExchange } from '../lib/product-library/productLibraryExchange.js';
import { addBuilderProduct, getBuilderCustomProducts, getBuilderOverrides, updateBuilderProductOverride, setCatalogueStorage, resetLegacyMigrationFlag, BUILDER_CUSTOM_PRODUCTS_STORAGE_KEY, BUILDER_OVERRIDES_STORAGE_KEY, getMasterProducts, getEffectiveProductCatalogue } from '../lib/product-library/catalogueService.js';
const records = new Map();
const storage = { getItem:key => records.get(key) ?? null, setItem:(key,value)=>records.set(key,String(value)), removeItem:key=>records.delete(key) };
setCatalogueStorage(storage); resetLegacyMigrationFlag();
const A='builder-a', B='builder-b';
storage.setItem(BUILDER_CUSTOM_PRODUCTS_STORAGE_KEY,JSON.stringify([{organisationId:A,productId:'original-a',productCode:'PRODUCT-A',familyKey:'kitchen-sinks',productName:'Product A',selectionSlotIds:['kitchen_sink']},{organisationId:B,productId:'original-b',productCode:'PRODUCT-B',familyKey:'kitchen-sinks',productName:'Product B'}]));
storage.setItem(BUILDER_OVERRIDES_STORAGE_KEY,JSON.stringify([{organisationId:A,masterProductCode:'PRODUCT-A',builderPrice:420},{organisationId:B,masterProductCode:'PRODUCT-B',builderPrice:390}]));
const legacy = storage.getItem(BUILDER_CUSTOM_PRODUCTS_STORAGE_KEY);
assert.equal(getBuilderCustomProducts(A).length,1); assert.equal(getBuilderCustomProducts(B).length,1);
assert.deepEqual(getBuilderCustomProducts(''),[]); assert.deepEqual(getBuilderOverrides(''),[]);
assert.equal(getBuilderOverrides(A)[0].builderPrice,420); assert.equal(getBuilderOverrides(B)[0].builderPrice,390);
updateBuilderProductOverride(A,'PRODUCT-A',{builderPrice:520});
assert.equal(getBuilderOverrides(A)[0].builderPrice,520); assert.equal(getBuilderOverrides(B)[0].builderPrice,390);
const renamed = addBuilderProduct(A,{...getBuilderCustomProducts(A)[0],description:'Changed description',productName:'Renamed'});
assert.equal(renamed.productId,'original-a'); assert.deepEqual(renamed.selectionSlotIds,['kitchen_sink']);
assert.throws(()=>addBuilderProduct(B,renamed),/another builder/);
assert.equal(storage.getItem(BUILDER_CUSTOM_PRODUCTS_STORAGE_KEY),legacy,'Migration retains original data for recovery');
assert(storage.getItem(tenantStorageKey(BUILDER_CUSTOM_PRODUCTS_STORAGE_KEY,A)));
assert(getMasterProducts().length>100,'Existing supplier Product Library loads');
assert(getEffectiveProductCatalogue({organisationId:A}).products.some(product=>product.productId==='original-a'));
assert(!getEffectiveProductCatalogue({organisationId:A}).products.some(product=>product.productId==='original-b'));
assert.throws(()=>getEffectiveProductCatalogue({organisationId:A,tenantId:B}),/Conflicting/);
assert.deepEqual(filterProductsForProductLibraryExchange([...getBuilderCustomProducts(A),...getBuilderCustomProducts(B)],{builderId:A,scope:'all'}).map(product=>product.productId),['original-a']);
globalThis.window={localStorage:storage,sessionStorage:storage};
storage.setItem('active_workspace_id',CURRENT_BUILDER_WORKSPACE_ID);
storage.setItem('estimate-builder-active-draft','original-job');
assert.equal(builderLocalStorage.getItem('estimate-builder-active-draft'),'original-job');
assert.equal(browserTenantKey('estimate-builder-template-db'),'estimate-builder-template-db');
const recoveredPath = 'recovery/quotation-order-2026-10-02/extracted/estimate.json';
if (fs.existsSync(recoveredPath)) {
  const saved = JSON.parse(fs.readFileSync(recoveredPath,'utf8')).workbook;
  const restored = scopeBrowserWorkbook(saved);
  assert.equal(restored.workspaceId,CURRENT_BUILDER_WORKSPACE_ID);
  assert.equal(restored.quotation,saved.quotation);
  assert.equal(restored.formulas,saved.formulas);
}
storage.setItem('active_workspace_id',B);
assert.equal(builderLocalStorage.getItem('estimate-builder-active-draft'),null);
builderLocalStorage.setItem('estimate-builder-active-draft','job-b');
assert.equal(storage.getItem('estimate-builder-active-draft'),'original-job');
assert.notEqual(browserTenantKey('estimate-builder-template-db'),'estimate-builder-template-db');
assert.throws(()=>scopeBrowserWorkbook({workspaceId:A}),/another builder/);
const fresh = createEstimateBuilderWorkbookDefaults({}, {workspaceId:B});
assert.deepEqual(fresh.quotation,{}); assert.deepEqual(fresh.standardInclusions.packages,[]); assert.equal(fresh.importedWorkbook,null);
const schedule = {packages:[{id:'signature',builder_id:B,name:'Signature Inclusions'}],sections:[{package_id:'signature',title:'Builder B custom section'}]};
assert.deepEqual(normaliseStandardInclusions(schedule,B).sections,schedule.sections);
assert.equal(normaliseStandardInclusions(schedule,B).packages[0].name,'Signature Inclusions');
delete globalThis.window;
console.log('PASS tenant browser storage, legacy preservation, product identity, prices, export isolation, existing catalogue loading and independent builder defaults.');
